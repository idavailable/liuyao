function relOf(q) {
  const s = C.suggestYongshen(q);
  return s ? s.rel : null;
}

MAIN.forEach(function (c) {
  eq('主集：' + c[0], relOf(c[0]), c[1]);
});
HOLDOUT.forEach(function (c) {
  eq('留出：' + c[0], relOf(c[0]), c[1]);
});

// ---------- 三、分层关系本身（不看单题，看结构）----------
// 主体 vs 事由：同一句事由，换了主体，用神必须跟着换
eq('主体优先：我为母亲问病取父母', relOf('我妈生病了'), '父母');
eq('主体优先：我为孩子问病取子孙', relOf('孩子生病了'), '子孙');
eq('占类改写能压过主体：占妻孕取子孙', relOf('老婆怀孕了吗'), '子孙');
eq('占类改写不越界：占妻财取妻财', relOf('老婆的工资能涨吗'), '妻财');

// 否定词不翻转归属（只改吉凶口径）
eq('否定：不打算买房仍属父母', relOf('不打算买房了'), '父母');
eq('否定：不想跳槽仍属官鬼', relOf('不想跳槽'), '官鬼');

// 词序无关：卖房 / 房子卖出去 同判妻财
eq('词序：卖房', relOf('卖房能卖多少'), '妻财');
eq('词序：房子卖出去', relOf('房子卖出去要多久'), '妻财');

// 多解题要给出次选，且次选不得与主选同六亲
const marry = C.suggestYongshen('什么时候能脱单');
eq('多解：脱单主取妻财', marry.rel, '妻财');
eq('多解：脱单次选官鬼（女占之解）', marry.alts.map(function (a) { return a.rel; }).indexOf('官鬼') >= 0, true);
const friend = C.suggestYongshen('朋友借钱不还');
eq('多解：朋友借钱主取兄弟', friend.rel, '兄弟');
eq('多解：朋友借钱次选妻财', friend.alts.map(function (a) { return a.rel; }).indexOf('妻财') >= 0, true);

// 推不出时返回 null（不猜），空输入不抛
eq('空串 → null', C.suggestYongshen(''), null);
eq('undefined → null', C.suggestYongshen(undefined), null);
eq('无实义词 → null', C.suggestYongshen('看看这个'), null);

// 推断结论必须能自证（why 非空），否则页面无法向用户解释为何取此用神
const explained = ['老婆怀孕了吗', '我妈的身体怎么样', '房子什么时候能卖出去', '考公能不能上岸'];
explained.forEach(function (q) {
  const s = C.suggestYongshen(q);
  eq('why 非空：' + q, !!(s && s.why), true);
});

