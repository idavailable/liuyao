  /** 按自定义事由里的语义线索推一个建议用神；命中不了就返回 null（宁缺勿强推）。 */
  function suggestYongshen(question) {
    const q = String(question == null ? '' : question);
    if (!q) return null;
    const keys = Object.keys(INTENT_YONGSHEN);
    for (let i = 0; i < keys.length; i++) {
      if (q.indexOf(keys[i]) >= 0) return { kw: keys[i], rel: INTENT_YONGSHEN[keys[i]] };
    }
    return null;
  }

